#1-1-1 format 格式化輸出
# 除此之外,為了輸出的美觀,Python 提供了格式化的輸出。
# 計有 format 和 % 兩種 格式。如下範例所示: 
#範例 1-1-1
a = 123
b = 123.456
c = 'python'

print(format(a, '15d'))
print(format(b, '10.2f'))
print(format(c, '10s'))
print()

# 程式中的 print() 主要的用意在於跳一空白行。
# 其中 5d 的 5 表示有5個欄位寬, d 表示是一整數。
# 10.2f中的 f 表示對應的是浮點數, 10.2 表示後面有2位小數點, 
# 有10個欄位寬,這10個欄位寬包含小數點。
# 10s 的 s 表示印出的是字串,而且其欄位寬為10。

print(format(a, '<5d'))
print(format(b, '<10.2f'))
print(format(c, '>10s'))
# 從輸出結果得知, Format 格式化輸出,字串的預設輸出是向左靠齊,
# 而整數和浮 點數是向右靠齊。
# 還好,我們可以利用  >  和 < 的符號做為向右向左靠齊的機制。
# 如輸出結果所示。若要置中,則可使用 ^ 符號。
print(format(a, '^5d'))
print(format(b, '^10.2f'))
print(format(c, '^10s'))

#1-1-2 ％ 格式化輸出
# 除了 format 的格式化輸出外,Pyhton 還提供了一個更方便的格式化輸出的利器, 
# 那就是 % ,其語法如下:
 
# print(‘%格式化字符’%(Variable_list))
# 以%為開頭,後接格式化字符,它可為d、f、s,這是第一個參數,並以單引號或 雙引號括住,
# 接下來是 % 再加上以小括號,括住每一個格式化字符所對應的變數。
# 如下範例所示: 

#範例 01
a = 123
b = 123.456
c = 'python'

# 表示 a 以 5d 的格式印出,注意, %的符號不可省略喔!其餘的依此類推。
# 在%的格式化中,不管整數、浮點數或是字串的輸出,皆是向右靠齊,
# 若要向左靠齊則必需加上負的符號 ' - '才可。所以
# 則是將結果靠左對齊。如輸出結果所示。
print('%-5d'%(a))
print('%-10.2f'%(b))
print('%-10s'%(c))

