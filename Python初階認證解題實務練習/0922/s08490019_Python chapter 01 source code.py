### 1-3 算術運算子 ------------------------------------------------------
# 程式在處理的過程中會用到運算子(operator)。
# 何謂運算子,其實它就是一個符 號,具有特殊的意義,
# 如上述的  = , 就是所謂的指定運算子(assignment operator), 
# 此運算子的功能就是將右邊的值指定給左邊的變數。
# 注意,由於是指定一定要是變數,因為變數才可以接收與改變其資料。 

# 除了上述的指定運算子外,一般的運算會常用到算術運算子,如表1-2 所示: 
# 表1-2 算術運算子 

# 運算子	功能說明
#   +	     加 
#   -	     減
#   *	     乘 
#   /	     除(結果是浮點數)
#   //	  除(結果是整數)
#   %	     兩數相除,取其餘數
#   **	  次方

# 數值計算的法則是先乘、除 , 後加、減。但小括號會改變其運算優先順序。
# 表1-2 要注意的是 :  / 運算子表示兩數相除,其結果是浮點數,亦即有小數點;
# 而 // 運算子,表示兩數相除取其整數 ; 
# %表示兩數相除取其餘數 , 
# 而** 表示乘以某 一數的幾次方。
# 我們以範例來加以說明: 

a = 100
b = a / 3
print(b)
#33.333333333333336

c = a // 3
print(c)
#1

f = a % 3
print(f)
#1

d = a ** 2
print(d)
#10000
e = a ** 0.5
print(e)
#10.0

